// Helper to generate monthly attendance grid for employees
export function generateMonthlyAttendance(): EmployeeMonthlyAttendance[] {
  const attendanceData: EmployeeMonthlyAttendance[] = [];

  MOCK_EMPLOYEES.slice(0, 15).forEach((emp) => {
    const days: { [day: number]: 'P' | 'A' | 'L' | 'H' | 'WFH' | 'WO' | 'HD' } = {};
    let present = 0;
    let absent = 0;
    let leave = 0;
    let halfDay = 0;
    let wfh = 0;

    for (let day = 1; day <= 31; day++) {
      // Oct 2026: 4, 11, 18, 25 are Sundays; 3, 10, 17, 24 are Saturdays
      const dayOfWeek = (day + 3) % 7; // Oct 1 is Thursday
      if (dayOfWeek === 0 || dayOfWeek === 6) {
        days[day] = 'WO';
      } else if (day === 2) {
        // Gandhi Jayanti
        days[day] = 'H';
      } else if (emp.status === 'On Leave' && day >= 10 && day <= 16) {
        days[day] = 'L';
        leave++;
      } else if (day === 12 && emp.employeeId === 'EMP005') {
        days[day] = 'A';
        absent++;
      } else if (day % 7 === 1 && emp.workLocation.includes('Remote')) {
        days[day] = 'WFH';
        wfh++;
      } else if (day === 8 && emp.employeeId === 'EMP003') {
        days[day] = 'HD';
        halfDay++;
      } else {
        days[day] = 'P';
        present++;
      }
    }

    attendanceData.push({
      employeeId: emp.employeeId,
      employeeName: `${emp.firstName} ${emp.lastName}`,
      department: emp.departmentName,
      avatar: emp.avatar,
      month: '2026-10',
      presentDays: present,
      absentDays: absent,
      leaveDays: leave,
      halfDays: halfDay,
      wfhDays: wfh,
      days,
    });
  });

  return attendanceData;
}

